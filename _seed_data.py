def seed_all():
    if fs.get_all_patients():
        return

    dr_kard = fs.add_practitioner(*_DR_KARD)
    dr_ther = fs.add_practitioner(*_DR_THER)

    for _pid, fam, giv, pat, gen, bd in _PATIENTS:
        fs.add_patient(fam, giv, pat, gen, bd)

    patients = fs.get_all_patients()
    for i, p in enumerate(patients):
        pid = p["id"]
        # приём у кардиолога с жалобой
        eid = fs.add_encounter(pid, practitioner_id=dr_kard, status="finished",
                               cls="ambulatory", start="2026-07-01",
                               complaint="Скачки давления, сердцебиение")
        # диагноз
        fs.add_condition(pid, "I10", "Гипертензивная болезнь",
                          onset_date="2024-01-01", encounter_id=eid)
        # АД
        _i, s, d, dt = _BP[i]
        fs.add_bp_observation(pid, s, d, obs_date=dt, encounter_id=eid)
        # препарат
        _j, atc, disp = _MEDS[i]
        fs.add_medication(pid, atc, disp, encounter_id=eid, med_date="2024-01-01")
        # путь
        st, lb = _PATHWAY[i]
        fs.set_pathway(pid, st, lb)
