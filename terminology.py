# и препараты, которые ГРУППА объединяет чисто по фармакологии, но КП №768 их не
# приравнивает (напр. J01CR: амоксициллин/клавуланат — первая линия, а
# пиперациллин/тазобактам из той же группы протоколом ВП не предусмотрен).
# Поэтому сверка «назначено то, что ожидает протокол» идёт не по группе, а по
# конкретному коду с явным списком допустимых клинических замен.
ATC_EQUIVALENT_GROUPS = [
    frozenset({"J01DD04", "J01DD01"}),  # цефтриаксон / цефотаксим
    frozenset({"J01MA12", "J01MA14"}),  # левофлоксацин / моксифлоксацин (резерв)
]


def abt_equivalent(actual_code, expected_code):
    """Является ли назначенный препарат самим ожидаемым или его протокольной заменой.

    Не путать с atc_group(): совпадение группы недостаточно, если группа объединяет
    клинически разные препараты (см. ATC_EQUIVALENT_GROUPS)."""
    if not actual_code or not expected_code:
        return False
    if actual_code == expected_code:
        return True
    return any(actual_code in g and expected_code in g for g in ATC_EQUIVALENT_GROUPS)


