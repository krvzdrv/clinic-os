def loinc_unit(code):
    entry = LOINC.get(code)
    return entry[1] if entry else ""

def loinc_reference(code):
    """Возвращает (low, high) референсного диапазона или (None, None)."""
    entry = LOINC.get(code)
    if not entry:
        return (None, None)
    return (entry[2], entry[3])

def interpret_value(code, value):
    """Норма / выше / ниже нормы по референсу. Возвращает 'normal'/'high'/'low'/None."""
    if value is None:
        return None
    low, high = loinc_reference(code)
    if low is None or high is None:
        return None
    if value > high:
        return "high"
    if value < low:
        return "low"
    return "normal"


# Пороги UI-бейджей осмотра (exam-vitals-section-form): клинические ярлыки, не LOINC-ref.
# SpO2 <95; t >38; АДс <90|>140; АДд <60; ЧСС >100|<60; ЧД >20|<12.
def vital_status_label(code, value):
    """Клинический ярлык вне нормы для витала или None (в норме / неизвестно)."""
    if value is None:
        return None
    try:
        v = float(value)
    except (TypeError, ValueError):
        return None
    if code == SPO2_CODE:
        if v < 95:
            return "ниже нормы"
    elif code == TEMP_CODE:
        if v > 38.0:
            return "лихорадка"
        if v < 35.5:
            return "гипотермия"
    elif code == SBP_CODE:
        if v < 90:
            return "гипотензия"
        if v > 140:
            return "гипертензия"
    elif code == DBP_CODE:
        if v < 60:
            return "гипотензия"
    elif code == HR_CODE:
        if v > 100:
            return "тахикардия"
        if v < 60:
            return "брадикардия"
    elif code == RR_CODE:
        if v > 20:
            return "тахипноэ"
        if v < 12:
            return "брадипноэ"
    return None


