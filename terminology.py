_DOSE_UNIT_TO_MG = {"мг": 1, "г": 1000, "мкг": 0.001}
# Комбинированная доза («875/125 мг») берём только первое (терапевтически значимое)
# число — второй компонент (напр. клавуланат) не входит в пороги ADULT_DOSES.
_DOSE_VALUE_RE = _re.compile(
    r"(\d+(?:[.,]\d+)?)(?:\s*/\s*\d+(?:[.,]\d+)?)?\s*(мг|г|мкг)\b", _re.IGNORECASE
)
_FREQ_TIMES_RE = _re.compile(r"(\d+)\s*раз", _re.IGNORECASE)


def parse_dose_per_day(dose_text, frequency_text):
    """Считает суточную дозу (мг/сут) из свободного текста полей «доза» и «кратность».

    Понимает формат каталога/протокола («500 мг», «2 г», «875/125 мг» + «1 раз в день»,
    «3 раза в день»). Если формат не распознан (диапазон, «по потребности», кратность
    не указана) — возвращает None, а не угадывает: лучше явно пропустить сверку дозы,
    чем молча посчитать неверное число.
    """
    if not dose_text or not frequency_text:
        return None
    m = _DOSE_VALUE_RE.search(str(dose_text))
    if not m:
        return None
    value = float(m.group(1).replace(",", "."))
    unit = m.group(2).lower()
    mg = value * _DOSE_UNIT_TO_MG.get(unit, 1)
    ft = str(frequency_text)
    if _re.search(r"1\s*раз\b", ft, _re.IGNORECASE):
        times = 1
    else:
        tm = _FREQ_TIMES_RE.search(ft)
        if not tm:
            return None
        times = int(tm.group(1))
    return round(mg * times, 1)
