def atc_group(code):
    """ATC-код -> (префикс группы уровня 4, название группы) или (None, None)."""
    if not code or len(code) < 5:
        return (None, None)
    prefix = code[:5]
    if prefix in ATC_GROUPS:
        return (prefix, ATC_GROUPS[prefix])
    return (None, None)

def atc_display(code):
    _prefix, name = atc_group(code)
    return name or code

def atc_drug_display(code):
    """Человекочитаемое название конкретного препарата (не группы)."""
    return ATC_DRUGS.get(code, atc_display(code))


# Внутри одной ATC-группы уровня 4 иногда встречаются препараты, которые протокол
